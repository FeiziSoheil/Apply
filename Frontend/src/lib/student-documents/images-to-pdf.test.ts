import { describe, expect, it } from "vitest";
import {
  buildJpegPagesPdf,
  mergeImagePagesToPdf,
  mergeWithPdfLib,
} from "./images-to-pdf";

/** Minimal valid JPEG (1×1 pixel) */
const TINY_JPEG = Uint8Array.from([
  0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01,
  0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0xff, 0xdb, 0x00, 0x43, 0x00, 0x08,
  0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0a,
  0x0c, 0x14, 0x0d, 0x0c, 0x0b, 0x0b, 0x0c, 0x19, 0x12, 0x13, 0x0f, 0x14, 0x1d,
  0x1a, 0x1f, 0x1e, 0x1d, 0x1a, 0x1c, 0x1c, 0x20, 0x24, 0x2e, 0x27, 0x20, 0x22,
  0x2c, 0x23, 0x1c, 0x1c, 0x28, 0x37, 0x29, 0x2c, 0x30, 0x31, 0x34, 0x34, 0x34,
  0x1f, 0x27, 0x39, 0x3d, 0x38, 0x32, 0x3c, 0x2e, 0x33, 0x34, 0x32, 0xff, 0xc0,
  0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xff, 0xc4,
  0x00, 0x14, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x08, 0xff, 0xc4, 0x00, 0x14, 0x10, 0x01,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
  0x7f, 0xff, 0xd9,
]);

describe("buildJpegPagesPdf", () => {
  it("builds a PDF header for one page", () => {
    const pdf = buildJpegPagesPdf([
      { jpeg: TINY_JPEG, width: 1, height: 1 },
    ]);
    const text = new TextDecoder("latin1").decode(pdf.slice(0, 8));
    expect(text).toBe("%PDF-1.4");
    expect(pdf.length).toBeGreaterThan(TINY_JPEG.length);
  });

  it("builds multi-page PDF", () => {
    const pdf = buildJpegPagesPdf([
      { jpeg: TINY_JPEG, width: 1, height: 1 },
      { jpeg: TINY_JPEG, width: 1, height: 1 },
    ]);
    const asText = new TextDecoder("latin1").decode(pdf);
    expect(asText).toContain("/Count 2");
    expect(asText).toContain("%%EOF");
  });

  it("throws on empty pages", () => {
    expect(() => buildJpegPagesPdf([])).toThrow(/صفحه/);
  });
});

describe("pdf-lib merge", () => {
  it("mergeWithPdfLib embeds a JPEG page", async () => {
    const bytes = await mergeWithPdfLib([
      {
        bytes: TINY_JPEG,
        mimeType: "image/jpeg",
        width: 1,
        height: 1,
      },
    ]);
    expect(bytes).not.toBeNull();
    const header = new TextDecoder("latin1").decode(bytes!.slice(0, 5));
    expect(header).toBe("%PDF-");
  });

  it("mergeImagePagesToPdf prefers pdf-lib and returns a File", async () => {
    const file = await mergeImagePagesToPdf(
      [
        {
          bytes: TINY_JPEG,
          mimeType: "image/jpeg",
          width: 1,
          height: 1,
        },
        {
          bytes: TINY_JPEG,
          mimeType: "image/jpeg",
          width: 1,
          height: 1,
        },
      ],
      "pages.pdf",
    );
    expect(file.type).toBe("application/pdf");
    expect(file.name).toBe("pages.pdf");
    expect(file.size).toBeGreaterThan(0);
  });
});
